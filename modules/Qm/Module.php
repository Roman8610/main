<?php

namespace app\modules\Qm;


/**
 * Модуль постановочных вопросов к совещаниям.
 *
 * Модуль предоставляет функциональность для работы с постановочными вопросами,
 * включая создание черновиков, модерацию, публикацию, комментирование,
 * проверку прав доступа и фильтрацию видимости вопросов.
 * Данные о совещаниях предоставляются путем интеграции с внешним модулем совещаний.
 *
 * Основные сущности:
 * - {@see \app\modules\Qm\models\Meeting} — совещание, к которому относится вопрос;
 * - {@see \app\modules\Qm\models\MeetingQuestion} — постановочный вопрос;
 * - {@see \app\modules\Qm\models\CommentQuestions} — комментарий к вопросу или другому комментарию.
 *
 * Состояния и переходы постановочного вопроса:
 * draft ───────→ pending ───────→ published
 *                  │                 │
 *                  ↓                 ↓
 *              rejected          removed
 *                  │                 │
 *                  └────→ pending    ├────→ published
 *                                    ├────→ rejected
 *                                    └────→ pending
 *
 * Статусы вопроса:
 * - draft — черновик, доступный автору для заполнения и редактирования;
 * - pending — вопрос отправлен на модерацию;
 * - published — вопрос опубликован и доступен пользователям совещания;
 * - rejected — вопрос отклонен модератором с указанием причины;
 * - removed — ранее опубликованный вопрос снят с публикации.
 *
 * Переходы между статусами:
 * - draft → pending — отправка автором вопроса на модерацию;
 * - pending → published — публикация вопроса руководителем совещания
 *   или администратором портала;
 * - pending → rejected — отклонение вопроса руководителем совещания
 *   или администратором портала;
 * - rejected → pending — повторная отправка автором отклоненного вопроса
 *   после доработки;
 * - published → removed — снятие опубликованного вопроса с публикации
 *   руководителем совещания или администратором портала;
 * - removed → published — повторная публикация снятого вопроса
 *   руководителем совещания или администратором портала;
 * - removed → rejected — отклонение снятого вопроса по результатам
 *   повторной проверки руководителем совещания или администратором портала;
 * - removed → pending — повторная отправка снятого вопроса автором
 *   на модерацию.
 *
 * @author Roman Drozdenko
 */
class Module extends \yii\base\Module
{
    public $controllerNamespace = 'app\modules\Qm\controllers';

    public function init()
    {
        parent::init();

        // custom initialization code goes here
    }
}
